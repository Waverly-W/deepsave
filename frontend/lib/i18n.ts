const translations: Record<Locale, TranslationDict> = {
  "zh-CN": zh,
  "en-US": en
};

export type TranslationKey = keyof typeof zh;

export const LANGUAGE_OPTIONS = [
  {
    value: "zh-CN",
    labelKey: "settings.language.option.zh.label",
    hintKey: "settings.language.option.zh.hint"
  },
  {
    value: "en-US",
    labelKey: "settings.language.option.en.label",
    hintKey: "settings.language.option.en.hint"
  }
] as const;

export const TYPE_LABEL_KEYS = {
  article: "type.article",
  image: "type.image",
  code: "type.code",
  note: "type.note"
} as const;

export const STATUS_LABEL_KEYS = {
  pending: "status.pending",
  processing: "status.processing",
  completed: "status.completed",
  failed: "status.failed",
  partial_fail: "status.partial_fail"
} as const;

export function resolveLocale(value?: string | null): Locale | null {
  if (!value) {
    return null;
  }
  const normalized = value.toLowerCase();
  if (normalized === "zh" || normalized === "zh-cn" || normalized === "zh-hans") {
    return "zh-CN";
  }
  if (normalized === "en" || normalized === "en-us") {
    return "en-US";
  }
  if (value === "zh-CN" || value === "en-US") {
    return value as Locale;
  }
  return null;
}

export function getLocaleOrDefault(value?: string | null): Locale {
  return resolveLocale(value) ?? DEFAULT_LOCALE;
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const template =
    translations[locale]?.[key] ??
    translations[DEFAULT_LOCALE][key] ??
    key;
  return formatTemplate(template, vars);
}

export function createTranslator(locale: Locale) {
  return (key: TranslationKey, vars?: Record<string, string | number>) =>
    translate(locale, key, vars);
}

export function getTypeLabel(locale: Locale, value: string): string {
  const key = TYPE_LABEL_KEYS[value as keyof typeof TYPE_LABEL_KEYS];
  return key ? translate(locale, key) : value;
}

export function getStatusLabel(locale: Locale, value: string): string {
  const key = STATUS_LABEL_KEYS[value as keyof typeof STATUS_LABEL_KEYS];
  return key ? translate(locale, key) : value;
}

function formatTemplate(
  template: string,
  vars?: Record<string, string | number>
): string {
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, key) => {
    const value = vars[key];
    if (value === undefined || value === null) {
      return match;
    }
    return String(value);
  });
}
